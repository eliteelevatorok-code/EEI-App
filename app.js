let ACCOUNTS = [];
function buildAccounts(){
  const m = new Map();
  ELEVATORS.forEach(e=>{
    const key = (e.email||"").toLowerCase() || ("no-email::"+(e.contact||e.loc));
    if(!m.has(key)) m.set(key,{key, name:e.contact||"(no contact name)", email:e.email||"", units:[]});
    m.get(key).units.push(e);
  });
  return [...m.values()].map(a=>{
    /* Label the account by its most common building prefix, shortest wins a tie.
       Longest would pick one odd building name and call the whole account that. */
    const stems = a.units.map(u=>u.loc.split(/\s[-#]/)[0].trim()).filter(Boolean);
    const freq = {}; stems.forEach(s=> freq[s]=(freq[s]||0)+1 );
    a.label = Object.keys(freq).sort((x,y)=> freq[y]-freq[x] || x.length-y.length)[0] || a.name;
    a.sites = new Set(a.units.map(u=>u.loc)).size;
    return a;
  }).sort((a,b)=> b.units.length - a.units.length);
}
function setRoster(list){
  ELEVATORS = list;
  try{ localStorage.setItem(ROSTER_KEY, JSON.stringify(list)); }catch(e){ STORAGE_OK=false; }
  ACCOUNTS = buildAccounts();
}

/* Reads their spreadsheet exported as CSV. Column order is the one their sheet uses:
   Oklahoma #, Location, Date Inspected, Date Due, Contact, email, Phone, maintenance, note */
function parseCsv(text){
  const NL=String.fromCharCode(10), CR=String.fromCharCode(13);
  const rows=[]; let row=[], cell="", q=false;
  for(let i=0;i<text.length;i++){
    const ch=text[i];
    if(q){
      if(ch==='"'){ if(text[i+1]==='"'){ cell+='"'; i++; } else q=false; }
      else cell+=ch;
    } else if(ch==='"') q=true;
    else if(ch===","){ row.push(cell); cell=""; }
    else if(ch===NL){ row.push(cell); rows.push(row); row=[]; cell=""; }
    else if(ch!==CR) cell+=ch;
  }
  if(cell.length||row.length){ row.push(cell); rows.push(row); }
  const out=[];
  rows.forEach(r=>{
    const c = r.map(x=>String(x||"").trim());
    if(c.length<4) return;
    if(!/^\d+$/.test(c[0])) return;                    // skips the header row and any blanks
    if(!/^\d+\/\d+\/\d{4}$/.test(c[3])) return;        // skips SCRAPPED / INACTIVE / MOD
    out.push({okla:c[0], loc:c[1], last:c[2], due:c[3], contact:c[4]||"",
              email:c[5]||"", phone:c[6]||"", prov:c[7]||"", note:c[8]||""});
  });
  return out;
}

