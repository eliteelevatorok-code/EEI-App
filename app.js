function renderOv(q){
  q=(q||"").trim().toLowerCase();
  const picked=new Set(rep?rep.viol.map(v=>v.text):[]);
  let html="", any=false;
  VIOLATION_STEPS.forEach(sec=>{
    const items=sec.items.filter(v=>!q||v.toLowerCase().includes(q));
    if(!items.length) return;
    any=true;
    html += `<div class="stephead"><b>${esc(sec.step)}</b> — ${esc(sec.head)}</div>`;
    html += items.map(v=>{
      const p=splitV(v);
      return `<button class="vpick ${picked.has(v)?"picked":""}" data-add="${esc(v)}">${esc(p.t)}<code>${esc(p.c)}</code></button>`;
    }).join("");
  });
  $("ovList").innerHTML = any ? html : `<p class="empty">Nothing matches.</p>`;
}
