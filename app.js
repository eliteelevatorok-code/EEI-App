/* ---------- tags ----------
   Plain labels stuck on an elevator (by Oklahoma number, so they stick across
   years, not per-report). No field in the app reads them automatically - they
   exist so Robert can see, later, which rule he's working under. */
function getTags(okla){ return (db[okla]||{}).tags || []; }
function saveTags(okla, tags){ db[okla]=db[okla]||{}; db[okla].tags=tags; writeDb(); }
function renderTags(){
  const tags = getTags(cur.okla);
  const chips = tags.map(t=>
    `<span class="tagchip">${esc(t)}${phoneMode?"":`<button data-untag="${esc(t)}" title="Remove">&times;</button>`}</span>`
  ).join("");
  const suggest = phoneMode ? "" : TAG_SUGGESTIONS.filter(t=>!tags.includes(t)).map(t=>
    `<span class="tagsuggest"><button data-addtag="${esc(t)}">+ ${esc(t)}</button></span>`).join("");
  const custom = phoneMode ? "" :
    `<span class="tagadd"><input id="tagCustom" placeholder="Custom tag"><button id="tagCustomAdd">Add</button></span>`;
  $("tagBar").innerHTML = chips + suggest + custom;
  $("tagBar").classList.toggle("on", tags.length>0 || !phoneMode);
}
document.addEventListener("click", e=>{
  if(!cur) return;
  const rm=e.target.closest("[data-untag]");
  if(rm){ saveTags(cur.okla, getTags(cur.okla).filter(t=>t!==rm.dataset.untag)); renderTags(); return; }
  const add=e.target.closest("[data-addtag]");
  if(add){ const t=add.dataset.addtag; const tags=getTags(cur.okla);
    if(!tags.includes(t)) saveTags(cur.okla, [...tags, t]); renderTags(); return; }
  if(e.target.id==="tagCustomAdd"){
    const inp=$("tagCustom"); const t=(inp.value||"").trim(); if(!t) return;
    const tags=getTags(cur.okla);
    if(!tags.includes(t)) saveTags(cur.okla, [...tags, t]); renderTags();
  }
});

